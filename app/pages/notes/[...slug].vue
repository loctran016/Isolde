// "a/b" + "../c" -> "a/c"
function joinPath(base: string, rel: string) {
  const out = base ? base.split('/') : []
  for (const part of rel.split('/')) {
    if (part === '..') out.pop()
    else if (part && part !== '.') out.push(part)
  }
  return out.join('/')
}

const wikiIndex = (() => {
  const byStem = new Map<string, string>()
  const byName = new Map<string, { stem: string; path: string }[]>()
  const walk = (items: NavigationItem[] = []) => {
    for (const i of items) {
      if (i.stem && i.page !== false) {
        const parts = i.stem.split('/')
        byStem.set(norm(i.stem), i.path)
        byStem.set(norm(parts.map(stripPrefix).join('/')), i.path)
        for (const key of new Set([norm(parts.at(-1)!), norm(stripPrefix(parts.at(-1)!))]))
          byName.set(key, [...(byName.get(key) ?? []), { stem: i.stem, path: i.path }])
      }
      walk(i.children)
    }
  }
  walk(nav.value)
  return { byStem, byName }
})()

function resolveWikiTarget(target: string): string | null {
  const raw = safeDecode(target).replace(/\.md$/i, '').trim()
  const stem = page.value!.meta.stem as string

  if (raw.includes('/')) {
    const dir = stem.split('/').slice(0, -1).join('/')
    for (const c of [joinPath(dir, raw), joinPath('', raw)]) {
      const hit = wikiIndex.byStem.get(norm(c))
      if (hit) return hit
    }
  }

  const cands = wikiIndex.byName.get(norm(raw.split('/').at(-1)!)) ?? []
  const top = stem.split('/')[0]
  return (cands.find((c) => c.stem.split('/')[0] === top) ?? cands[0])?.path ?? null
}

const WIKI = /\[\[([^\]|#]+?)(?:#[^\]|]*)?(?:\|([^\]]*))?\]\]/g

function splitWiki(text: string): any[] {
  const out: any[] = []
  let last = 0
  for (const m of text.matchAll(WIKI)) {
    const at = m.index!
    if (at > last) out.push(text.slice(last, at))
    const label =
      m[2]?.trim() || stripPrefix(safeDecode(m[1]).replace(/\.md$/i, '').split('/').at(-1)!)
    const href = resolveWikiTarget(m[1])
    out.push(
      href
        ? ['a', { href, class: 'wikilink' }, label]
        : ['span', { class: 'opacity-60', title: 'Không tìm thấy ghi chú' }, label],
    )
    last = at + m[0].length
  }
  if (last < text.length) out.push(text.slice(last))
  return out.length ? out : [text]
}

// Plain text of a node (strings plus the text inside links/spans)
const textOf = (n: any): string =>
  typeof n === 'string' ? n : Array.isArray(n) ? n.slice(2).map(textOf).join('') : ''

// Comark turns "[[x]]" into span > span > x, so look for that shape
const isWikiSpan = (n: any) =>
  Array.isArray(n) &&
  n[0] === 'span' &&
  Object.keys(n[1] ?? {}).length === 0 &&
  n.length === 3 &&
  Array.isArray(n[2]) &&
  n[2][0] === 'span' &&
  Object.keys(n[2][1] ?? {}).length === 0

function wikiNode(raw: string): any {
  const [targetPart, ...rest] = raw.split('|')
  const target = targetPart.split('#')[0].trim()
  const alias = rest.join('|').trim()
  const label = alias || stripPrefix(safeDecode(target).replace(/\.md$/i, '').split('/').at(-1)!)
  const href = target ? resolveWikiTarget(target) : null
  return href
    ? ['a', { href, class: 'wikilink' }, label]
    : ['span', { class: 'opacity-60', title: 'Không tìm thấy ghi chú' }, label]
}

const rewriteWikilinks = (nodes: any[]) => {
  for (const n of nodes) {
    if (!Array.isArray(n) || ['code', 'pre', 'a'].includes(n[0])) continue

    // Join adjacent text pieces first, in case a plain "[[...]]" is ever split up
    const merged: any[] = []
    for (const k of n.slice(2)) {
      if (typeof k === 'string' && typeof merged.at(-1) === 'string') merged[merged.length - 1] += k
      else merged.push(k)
    }

    const kids = merged.flatMap((k) => {
      if (typeof k === 'string') return splitWiki(k) // literal [[...]] text, if any survives
      if (isWikiSpan(k)) return [wikiNode(textOf(k))] // the span > span shape
      return [k]
    })
    n.splice(2, n.length - 2, ...kids)
    rewriteWikilinks(kids)
  }
}
rewriteWikilinks(page.value.nodes)

const rewriteImgs = (nodes: any[]) => {
  for (const n of nodes) {
    if (!Array.isArray(n)) continue
    if (n[0] === 'img') {
      const props = (n[1] ??= {})
      const raw = (props.src || props.alt || '').trim()
      if (raw && !/^(https?:)?\/\/|^data:|^\//.test(raw)) {
        const key = `${noteDir}/${decodeURIComponent(raw)}`
        props.src = '/media/' + key.split('/').slice(1).map(encodeURIComponent).join('/')
        // props.src = '/api/content/media/' + key.split('/').map(encodeURIComponent).join('/')
        // This come from /api/content/media/, others related code is still there, including addServeHandler and media()
      }
    }
    rewriteImgs(n.slice(2))
  }
}
rewriteImgs(page.value.nodes)

// Text shortcuts: "=>" becomes "⇒", "<=" becomes "≤" and so on.
// Code, code blocks and mermaid diagrams are left untouched.
const symbols: Record<string, string> = {
  '<=>': '⇔',
  '<->': '↔',
  '=>': '⇒',
  '->': '→',
  '<-': '←',
  '<=': '≤',
  '>=': '≥',
  '!=': '≠',
  '+/-': '±',
  '~=': '≈',
  '<==>': '⟺',
  '<-->': '⟷',
  '==>': '⟹',
  '-->': '⟶',
  '—>': '⟶',
  '<==': '⟸',
  '<--': '⟵',
}
// longest patterns first so "<==>" is not split into "<=" + "=>"
const symbolRe = /<==>|<-->|<=>|<->|==>|-->|—>|<==|<--|\+\/-|<=|>=|!=|~=|=>|->|<-/g
const skipTags = new Set(['code', 'pre', 'mermaid', 'math', 'script', 'style'])

const replaceSymbols = (nodes: any[]) => {
  for (const n of nodes) {
    if (!Array.isArray(n) || skipTags.has(n[0])) continue
    for (let i = 2; i < n.length; i++) {
      if (typeof n[i] === 'string') {
        n[i] = n[i].replace(symbolRe, (m: string) => symbols[m])
      } else {
        replaceSymbols([n[i]])
      }
    }
  }
}
replaceSymbols(page.value.nodes)

// Wrap every table in a scroll container ("overflow" does nothing on a <table> itself).
// The wrapper is skipped when it already exists, because this runs on the server and again
// on the client, and a second pass must not wrap the table twice.
const wrapTables = (children: any[], start = 0) => {
  for (let i = start; i < children.length; i++) {
    const n = children[i]
    if (!Array.isArray(n) || skipTags.has(n[0])) continue
    if (n[0] === 'div' && n[1]?.class === 'table-wrap') continue
    if (n[0] === 'table') children[i] = ['div', { class: 'table-wrap' }, n]
    else wrapTables(n, 2)
  }
}
wrapTables(page.value.nodes)

// ---- Parse test (dev only): what AST does each plugin set produce for a given markdown? ----
// Auto-runs when the URL has ?parseTest. You can also call it from the browser console:
//   __comarkTest()                                        -> the built-in multimd sample
//   __comarkTest('| a | b |\n|---|---|\n| 1 | 2 |')        -> your own markdown
const PARSE_SAMPLE = String.raw`|             | Grouping            ||
| First       | Second   | Third    |
| ----------- | :------: | -------: |
| Colspan     | Long cell spanning  ||
| Rowspan     | **Cell** | Cell     |
| ^^          | Cell     | Cell     |
| Multiline   | Line one | C1       | \
|             | Line two | C2       |
[Prototype table]

|-------------|----------|
| Headerless  | table    |
`

const walkNodes = (nodes: any[], fn: (n: any[]) => void) => {
  for (const n of nodes) {
    if (!Array.isArray(n)) continue
    fn(n)
    walkNodes(n.slice(2), fn)
  }
}

async function runParseTest(markdown: string = PARSE_SAMPLE) {
  const mod: any = await import('comark')
  const parseFn = mod.parse ?? mod.parseMarkdown // the export was renamed between versions
  if (typeof parseFn !== 'function') {
    console.warn('[parse test] no parse()/parseMarkdown() export in "comark". Exports:', Object.keys(mod))
    return
  }

  const cases: { name: string; plugins: any[] }[] = [
    { name: 'no plugins', plugins: [] },
    { name: 'multimd-table only', plugins: [multimdTable()] },
    { name: 'page plugins (toc + multimd + mermaid)', plugins },
  ]

  for (const c of cases) {
    const t0 = performance.now()
    try {
      const result = await parseFn(markdown, { plugins: c.plugins })

      const tags: Record<string, number> = {}
      const spans: string[] = []
      walkNodes(result.nodes, (n) => {
        tags[n[0]] = (tags[n[0]] ?? 0) + 1
        const a = n[1] ?? {}
        const rowspan = a.rowspan ?? a.rowSpan
        const colspan = a.colspan ?? a.colSpan
        if ((n[0] === 'td' || n[0] === 'th') && (rowspan || colspan))
          spans.push(`${n[0]} rowspan=${rowspan ?? 1} colspan=${colspan ?? 1}: ${textOf(n).trim().slice(0, 30)}`)
      })

      // Multimd syntax that survived into the output means the plugin did not apply
      const json = JSON.stringify(result.nodes)
      const leftover = ['^^', '||'].filter((s) => json.includes(s))

      console.groupCollapsed(`[parse test] ${c.name} (${(performance.now() - t0).toFixed(1)} ms)`)
      console.log('nodes:', result.nodes)
      console.table(tags)
      console.log('cells with rowspan/colspan:', spans.length ? spans : 'none found')
      console.log('multimd syntax left unparsed:', leftover.length ? leftover : 'none')
      console.groupEnd()
    } catch (err) {
      console.error(`[parse test] "${c.name}" threw:`, err)
    }
  }
}

onMounted(() => {
  if (!import.meta.dev) return
  ;(window as any).__comarkTest = runParseTest
  if ('parseTest' in route.query) runParseTest()
})

const topHeading = computed(() => {
  let min = 7
  const walk = (nodes: any[]) => {
    for (const n of nodes) {
      if (!Array.isArray(n)) continue
      const m = /^h([1-6])$/.exec(String(n[0]))
      if (m) min = Math.min(min, Number(m[1]))
      walk(n.slice(2))
    }
  }
  walk(page.value?.nodes ?? [])
  return min === 7 ? 2 : min
})
